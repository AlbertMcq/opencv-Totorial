# OpenCV 绘制图形示例 - 直线、矩形、圆形和文字
import cv2
import numpy as np

# 创建一个 300x300 的黑色画布，3个通道(BGR)
# np.zeros 创建全0数组，dtype=np.uint8 表示8位无符号整数(0-255)
image = np.zeros([300, 300, 3], dtype=np.uint8)

# 绘制直线
# 参数：图像, 起点坐标, 终点坐标, 颜色(BGR), 线条粗细
# (255, 0, 0) 表示蓝色
cv2.line(image, (100, 200), (250, 250), (255, 0, 0), 2)

# 绘制矩形
# 参数：图像, 左上角坐标, 右下角坐标, 颜色(BGR), 线条粗细
# (0, 255, 0) 表示绿色
cv2.rectangle(image, (30,100), (60,150), (0, 255, 0), 2)

# 绘制圆形
# 参数：图像, 圆心坐标, 半径, 颜色(BGR), 线条粗细
# (0, 0, 255) 表示红色
cv2.circle(image, (150,100), 20, (0,0,255), 3)

# 添加文字
# 参数：图像, 文字内容, 起始坐标, 字体类型, 字体大小, 颜色(BGR), 线条粗细, 线型
# 0 表示 FONT_HERSHEY_SIMPLEX 字体，(255,255,255) 表示白色
cv2.putText(image, "Hello", (100,50), 0, 1, (255,255,255), 2, 1)

# 显示绘制好的图像
cv2.imshow("image", image)
# 等待用户按任意键后关闭窗口
cv2.waitKey()





